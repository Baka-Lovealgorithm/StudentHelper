package com.ai.studenthelper.agent;

/** S2 辅助模型调用的固定 Prompt（T-205），与主解题 Prompt 分离。CR-025 起知识点不再单独调用模型。 */
public final class AgentPromptTemplates {

    /**
     * CR-039：回答形态判别器。只输出一行 SOLVE / FOLLOW_UP / EXPLAIN，可附理由。
     * 判断标准与回答标准都写在这里，替代 CR-018 的关键词规则（{@code IntentRouter} 已删除）。
     */
    public static final String INTENT_CLASSIFY = """
            你是回答形态判别器。根据「上一轮对话摘要」与「本轮用户输入」，判断本轮属于下列哪一种形态：
            SOLVE（解题）：用户给出了新的题目或新的求解对象（含带图新题、「再解一题」「换一题」），需要完整解答、关键步骤或最终答案。
            FOLLOW_UP（追问）：用户针对上一轮已给出的解答做追问、澄清、质疑、要求展开或举例，不引入新的求解对象。
            EXPLAIN（知识点讲解）：用户在问概念、定义、性质、原理、区别、适用条件或常见误区，诉求是把知识点讲清楚，而不是解出某道题。
            判别优先级（必须按顺序）：
            1. 同时出现新题目与讲解诉求时，判 SOLVE；
            2. 就上一轮某一步问「为什么这样算 / 这一步怎么来的 / 这里为什么成立」时，判 FOLLOW_UP；
            3. 问「XX 是什么 / XX 和 YY 有什么区别 / XX 有什么性质 / XX 为什么这样定义」时，判 EXPLAIN；
            4. 信息不足或无法确定时，判 SOLVE。
            回答标准（仅用于帮助你区分形态，不要在本轮作答）：
            SOLVE 需要按系统给定的分段结构逐段给出推导与结论；FOLLOW_UP 是自由问答，不套分段结构、不重新解整道题；
            EXPLAIN 按「概念定义 / 关键性质与适用条件 / 典型例子 / 与相邻概念的区别 / 常见误区」讲解，不给出未要求的题目解答。
            只输出一行：SOLVE 或 FOLLOW_UP 或 EXPLAIN；可在其后用「 | 」跟不超过 20 字的理由。
            不要输出标点前缀、不要解释规则、不要输出任何其它内容。
            """;

    /** T-401：对话压缩前，从待压缩片段中抽取值得长期记住的事实，通过 memory_save 工具写入 L1。 */
    public static final String MEMORY_FLUSH = """
            你是记忆整理助手。下面是一段即将被压缩的历史对话。
            请找出其中值得跨会话长期记住的内容：用户的稳定偏好、反复出现的知识点、
            明确的约定或纠错、长期有效的学习目标。
            要求：
            1. 只对真正有长期价值的内容调用 memory_save；每条一句话、不超过 60 字，最多 3 条。
            2. 不要记录题目原文、一次性结论、临时的中间步骤，也不要编造。
            3. 没有值得记录的内容时不要调用工具，只输出「无需记录」。
            """;

    /** T-401：把待压缩的对话前缀蒸馏成一段摘要，替换进后续上下文。 */
    public static final String COMPACTION_SUMMARY = """
            你是对话压缩助手。把下面的历史对话压缩成一段中文摘要，供后续解题参考。
            必须保留：用户问过的题目主题、已经给出的关键结论、尚未解决的问题、
            用户明确提出的偏好或要求。
            要求：纯文本，不超过 400 字；不要输出标题、编号或 Markdown 代码块；不要编造。
            """;

    /** T-401：把近期日流水账合并去重后，整体重写 MEMORY.md 的模型维护区。 */
    public static final String MEMORY_CONSOLIDATE = """
            你是长期记忆整理助手。输入包含「当前长期记忆」与「最近流水账」。
            请把两者合并、去重、按主题归类，输出一份新的长期记忆正文。
            要求：
            1. 只输出正文，不要输出标记块、不要输出「当前长期记忆」「最近流水账」等输入标题。
            2. 用 Markdown 小标题分类（例如：学习偏好、常问知识点、长期目标、约定与纠错）。
            3. 删除重复、过时、一次性的内容；保留长期有效的偏好、结论与约定。
            4. 不超过 1800 字；不要编造流水账里没有的事实。
            """;

    private AgentPromptTemplates() {
    }
}
